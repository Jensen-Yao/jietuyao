#!/usr/bin/env python3
"""从 jietuyao v1 的 SVG 图标生成 C# 静态图标类（WPF Path 渲染）。
用法: python gen_icons.py <svg_dir> <output_cs>
"""
import re
import sys
from pathlib import Path

# 图标名 → C# 属性名（仅提取需要的）
ICONS = {
    "选择.svg": "Select",
    "画笔.svg": "Pen",
    "荧光笔.svg": "Highlighter",
    "方框.svg": "Rectangle",
    "圆框.svg": "Ellipse",
    "箭头.svg": "Arrow",
    "文字.svg": "Text",
    "序号.svg": "Number",
    "橡皮.svg": "Eraser",
    "鼠标.svg": "Cursor",
    "撤回.svg": "Undo",
    "复制.svg": "Copy",
    "保存.svg": "Save",
    "钉图.svg": "Pin",
    "ocr.svg": "Ocr",
    "翻译.svg": "Translate",
    "关闭.svg": "Close",
    "圆角.svg": "RoundedCorner",
    "阴影描边.svg": "ShadowBorder",
    "保持纵横比.svg": "LockRatio",
    "刷新背景.svg": "RefreshBackground",
    "确定.svg": "Confirm",
    "颜色设置.svg": "ColorSettings",
    "长截图.svg": "LongScreenshot",
    "gif.svg": "Gif",
}

PATH_RE = re.compile(r"<path\b([^>]*?)(?:/>|>)", re.S)
D_RE = re.compile(r'\bd="([^"]+)"')
SW_RE = re.compile(r'\bstroke-width="([\d.]+)"')
FILL_RE = re.compile(r'\bfill="([^"]*)"')
VIEWBOX_RE = re.compile(r'\bviewBox="([-\d.\s]+)"')
WIDTH_RE = re.compile(r'<svg[^>]*\bwidth="([\d.]+)"')
HEIGHT_RE = re.compile(r'<svg[^>]*\bheight="([\d.]+)"')
ROOT_SW_RE = re.compile(r'stroke-width="([\d.]+)"')


def parse_svg(text: str):
    vb = VIEWBOX_RE.search(text)
    if vb:
        nums = [float(x) for x in vb.group(1).split()]
        if len(nums) == 2:
            nums = [0, 0, nums[0], nums[1]]
        min_x, min_y, w, h = nums
    else:
        mw = WIDTH_RE.search(text)
        mh = HEIGHT_RE.search(text)
        if not (mw and mh):
            return None
        min_x, min_y, w, h = 0.0, 0.0, float(mw.group(1)), float(mh.group(1))
    # 根节点默认描边宽度
    head = text[: text.find("<path")] if "<path" in text else text
    root_sw = ROOT_SW_RE.search(head)
    default_sw = float(root_sw.group(1)) if root_sw else 2.0

    paths = []
    for m in PATH_RE.finditer(text):
        attrs = m.group(1)
        d = D_RE.search(attrs)
        if not d:
            continue
        sw = SW_RE.search(attrs)
        fill = FILL_RE.search(attrs)
        stroke_width = float(sw.group(1)) if sw else default_sw
        is_fill = fill is not None and fill.group(1).lower() not in ("none", "")
        paths.append((d.group(1), stroke_width, is_fill))

    # rect/circle 基本图形转 path 数据
    for m in re.finditer(r"<rect\b([^>]*?)(?:/>|>)", text):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(1)))
        try:
            rx, ry = float(a.get("x", 0)), float(a.get("y", 0))
            rw, rh = float(a.get("width", 0)), float(a.get("height", 0))
        except ValueError:
            continue
        if rw <= 0 or rh <= 0:
            continue
        r = min(float(a.get("rx", 0) or 0), rw / 2, rh / 2)
        if r > 0:
            d = (f"M{rx + r} {ry} H{rx + rw - r} A{r} {r} 0 0 1 {rx + rw} {ry + r} "
                 f"V{ry + rh - r} A{r} {r} 0 0 1 {rx + rw - r} {ry + rh} "
                 f"H{rx + r} A{r} {r} 0 0 1 {rx} {ry + rh - r} V{ry + r} A{r} {r} 0 0 1 {rx + r} {ry} Z")
        else:
            d = f"M{rx} {ry} H{rx + rw} V{ry + rh} H{rx} Z"
        fill = a.get("fill", "none")
        paths.append((d, float(a.get("stroke-width", default_sw) or default_sw), fill.lower() not in ("none", "")))

    for m in re.finditer(r"<circle\b([^>]*?)(?:/>|>)", text):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(1)))
        try:
            cx, cy, r = float(a.get("cx", 0)), float(a.get("cy", 0)), float(a.get("r", 0))
        except ValueError:
            continue
        if r <= 0:
            continue
        d = (f"M{cx - r} {cy} A{r} {r} 0 0 1 {cx + r} {cy} A{r} {r} 0 0 1 {cx - r} {cy} Z")
        fill = a.get("fill", "none")
        paths.append((d, float(a.get("stroke-width", default_sw) or default_sw), fill.lower() not in ("none", "")))

    if not paths:
        return None
    return (min_x, min_y, w, h, paths)


def cs_escape(s: str) -> str:
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\r\n", " ").replace("\n", " ").replace("\r", " ").replace("\t", " "))


def main(svg_dir: str, out_cs: str):
    lines = []
    lines.append("// <auto-generated/>")
    lines.append("// 由 tools/gen_icons.py 从 jietuyao v1 SVG 图标生成，勿手改")
    lines.append("using System.Windows;");
    lines.append("")
    lines.append("namespace STranslate.Core;")
    lines.append("")
    lines.append("/// <summary>jietuyao 自家 SVG 图标（WPF Path 渲染数据）</summary>")
    lines.append("public static class JietuyaoIcons")
    lines.append("{")
    lines.append("    /// <summary>单条路径：数据/描边宽度/是否填充</summary>")
    lines.append("    public sealed record IconPath(string Data, double StrokeWidth, bool IsFill);")
    lines.append("")
    lines.append("    /// <summary>图标定义：viewBox 最小 XY 与宽高（用于归一化缩放）</summary>")
    lines.append("    public sealed record IconDef(double MinX, double MinY, double Width, double Height, IconPath[] Paths);")
    lines.append("")

    missing = []
    for file, prop in ICONS.items():
        p = Path(svg_dir) / file
        if not p.exists():
            missing.append(file)
            continue
        parsed = parse_svg(p.read_text(encoding="utf-8", errors="ignore"))
        if parsed is None:
            missing.append(file)
            continue
        min_x, min_y, w, h, paths = parsed
        items = ",\n        ".join(
            f'new IconPath("{cs_escape(d)}", {sw}, {"true" if is_fill else "false"})'
            for d, sw, is_fill in paths
        )
        lines.append(f"    public static readonly IconDef {prop} = new({min_x}, {min_y}, {w}, {h},")
        lines.append("        [")
        lines.append(f"        {items}")
        lines.append("        ]);")
        lines.append("")

    lines.append("}")
    Path(out_cs).write_text("\n".join(lines), encoding="utf-8")
    print(f"生成 {out_cs}: {len(ICONS) - len(missing)}/{len(ICONS)} 图标")
    if missing:
        print("缺失:", missing)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
